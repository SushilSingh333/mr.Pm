/**
 * Bake the logo lockup into a module the proposal PDF can embed.
 *
 * The PDF is written byte by byte with hand-rolled primitives, so it cannot fetch an
 * image at render time - whatever it draws has to be inside the bundle. A PDF image
 * XObject takes raw JPEG bytes directly (`/Filter /DCTDecode`), so the artwork is
 * emitted here as base64 and decoded with `atob` when a proposal is generated.
 *
 * JPEG rather than PNG because a PDF can embed JPEG with no re-encoding, while PNG
 * would need its alpha unpacked into a separate soft-mask object. The lockup is
 * flattened onto the masthead colour instead, which is exactly what the transparency
 * would have resolved to anyway.
 *
 * 600px wide for a mark displayed around 150pt: 4x, so it stays crisp when a customer
 * zooms in or prints the quote.
 *
 * Re-run after changing the logo artwork or the masthead colour:
 *   node scripts/build-pdf-logo.mjs
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(path.resolve('apps/cms/package.json'));
const sharp = require('sharp');

const SRC = path.join('apps', 'web', 'public', 'logo-lockup-inverse.png');
const OUT = path.join('apps', 'cms', 'src', 'components', 'proposal', 'logo-data.ts');
/** Must match CO.deep in proposal-pdf.ts, or the flattened edge shows a seam. */
const MASTHEAD = '#0f0063';
const WIDTH = 600;

const { data, info } = await sharp(SRC)
  .resize({ width: WIDTH })
  .flatten({ background: MASTHEAD })
  .jpeg({ quality: 88, mozjpeg: true })
  .toBuffer({ resolveWithObject: true });

const b64 = data.toString('base64');
const lines = b64.match(/.{1,96}/g) ?? [];

await writeFile(
  OUT,
  `/**
 * GENERATED by scripts/build-pdf-logo.mjs - do not edit by hand.
 *
 * The MrMoverPacker lockup as a baseline JPEG, ready to drop into a PDF image
 * XObject with /Filter /DCTDecode. Flattened onto the masthead colour ${MASTHEAD},
 * so it must be regenerated if that colour changes.
 */
export const PDF_LOGO = {
  width: ${info.width},
  height: ${info.height},
  /** Base64 JPEG. Decode with atob() to get the raw bytes the PDF stream needs. */
  base64:
${lines.map((l) => `    '${l}'`).join(' +\n')},
};
`,
  'utf8',
);

console.info(
  `  ${info.width}x${info.height} JPEG, ${(data.length / 1024).toFixed(1)} KB` +
    ` (${(b64.length / 1024).toFixed(1)} KB base64)\n  wrote ${OUT}`,
);
